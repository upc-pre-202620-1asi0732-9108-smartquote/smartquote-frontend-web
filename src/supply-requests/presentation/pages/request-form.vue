<script setup>
import { ref, onMounted } from "vue";
import { useI18n } from "vue-i18n";
import { useRoute, useRouter } from "vue-router";
import Button from "primevue/button";
import InputText from "primevue/inputtext";
import Select from "primevue/select";
import Field from "../../../shared/presentation/components/form-field.vue";
import Feedback from "../../../shared/presentation/components/feedback-notice.vue";
import ItemsEditor from "../components/request-items-editor.vue";
import {
  isoDate,
  newItem,
  toEditableItems,
} from "../components/request-item-defaults.js";
import {
  useWorkspace,
  useFeedback,
} from "../../../shared/presentation/use-workspace.js";
const { t } = useI18n(),
  route = useRoute(),
  router = useRouter(),
  { session, services } = useWorkspace();
const { busy, error, execute } = useFeedback();
// US16: the same form edits a draft generated by a recurring schedule.
const draftId = route.params.id,
  draft = ref(null);
const suggestedDate = new Date();
suggestedDate.setDate(suggestedDate.getDate() + 7);
const todayIso = new Date().toLocaleDateString("en-CA");
const form = ref({
  requiredDate: isoDate(suggestedDate),
  priority: "Normal",
  items: [newItem()],
});
onMounted(() => {
  if (draftId)
    execute(async () => {
      const current = await services.value.requests.get(draftId);
      draft.value = current;
      form.value = {
        requiredDate: current.requiredDate,
        priority: current.priority,
        items: toEditableItems(current.items),
      };
    });
});
async function submit() {
  const result = await execute(() =>
    draftId
      ? services.value.requests.editDraft(draft.value, form.value)
      : services.value.requests.create(form.value),
  );
  if (result) router.push("/requests/" + result.requestId);
}
</script>
<template>
  <Button
    :label="t('back')"
    icon="pi pi-arrow-left"
    text
    :disabled="busy"
    @click="router.push(draftId ? '/requests/' + draftId : '/requests')"
  />
  <div class="page-heading">
    <div>
      <h1>{{ draftId ? t("editDraft") : t("newRequest") }}</h1>
      <p class="muted">{{ draftId ? t("editDraftIntro") : t("requestFormIntro") }}</p>
    </div>
  </div>
  <Feedback :error="error" />
  <p v-if="!session.production" class="empty-state">
    {{ t("productionOnly") }}
  </p>
  <p v-else-if="draftId && !draft" class="empty-state" role="status">
    {{ busy ? t("loading") : t("draftUnavailable") }}
  </p>
  <p v-else-if="draft && !draft.isDraft" class="empty-state">
    {{ t("draftUnavailable") }}
  </p>
  <form v-else @submit.prevent="submit" class="stack">
    <fieldset :disabled="busy" class="form-fieldset">
      <div class="panel form-grid">
        <Field :label="t('requiredDate')" v-slot="{ id }"
          ><InputText
            :id="id"
            v-model="form.requiredDate"
            type="date"
            :min="todayIso"
            required /></Field
        ><Field :label="t('priority')" v-slot="{ id }"
          ><Select
            :input-id="id"
            :aria-label="t('priority')"
            v-model="form.priority"
            :options="
              ['Normal', 'High', 'Emergency'].map((value) => ({
                value,
                label: t('priorities.' + value),
              }))
            "
            option-label="label"
            option-value="value"
        /></Field>
      </div>
      <ItemsEditor v-model="form.items" />
    </fieldset>
    <div class="actions">
      <Button
        type="submit"
        :label="draftId ? t('saveDraft') : t('submitRequest')"
        icon="pi pi-check"
        :loading="busy"
      />
    </div>
  </form>
</template>
